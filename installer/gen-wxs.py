"""Generate Package.wxs for the Filesa COChat MSI installer.

The application ships as 267 loose files in a folder tree (WinUI 3 + the
self-contained Windows App SDK, including per-language .mui folders), so the WiX
source is generated instead of hand-maintained: rerun this script whenever
dist/ changes, then build with build-installer.ps1.

Two things matter for correctness:
  * the destination directory tree must mirror dist/, otherwise the .mui
    resources and Assets/ land flattened in the install root;
  * component GUIDs are uuid5 of the file's relative path, so they stay stable
    across rebuilds - that is what lets MajorUpgrade replace an older version.
"""
import pathlib
import re
import uuid
from xml.sax.saxutils import escape

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent


def product_version() -> tuple[str, str]:
    """Read the display version from Core/AppInfo.cs and pad it for MSI.

    Keeping one source of truth means the payload folder, the MSI ProductVersion
    and the About page can never disagree.
    """
    text = (ROOT / "src" / "FilesaCOChat.Core" / "AppInfo.cs").read_text(encoding="utf-8")
    match = re.search(r'const string Version = "([0-9]+(?:\.[0-9]+)*)"', text)
    if not match:
        raise SystemExit("could not find AppInfo.Version")
    display = match.group(1)
    parts = display.split(".")
    if len(parts) > 3:
        raise SystemExit(f"MSI needs at most 3 version fields, got {display}")
    return display, ".".join(parts + ["0"] * (3 - len(parts)))


VERSION, PRODUCT_VERSION = product_version()
DIST = ROOT / "dist" / f"FilesaCOChat-{VERSION}-win-x64"
UPGRADE_CODE = "{8C1F3A52-6B7D-4E23-9E3C-5A1B2D4C7E90}"
GUID_NS = uuid.UUID("6f9619ff-8b86-d011-b42d-00cf4fc964ff")
EXE_NAME = "FilesaCOChat.WinUI.exe"
ATTR_ESCAPES = {'"': "&quot;"}


def guid_for(key: str) -> str:
    return "{" + str(uuid.uuid5(GUID_NS, key)).upper() + "}"


def main() -> None:
    if not DIST.is_dir():
        raise SystemExit(f"dist folder not found: {DIST}")

    files = sorted((p for p in DIST.rglob("*") if p.is_file()),
                   key=lambda p: p.relative_to(DIST).as_posix().lower())
    if not files:
        raise SystemExit(f"no files to package in {DIST}")

    # ---- directory tree: relative posix dir -> MSI Directory Id ----------
    dir_ids: dict[str, str] = {"": "INSTALLFOLDER"}
    for path in files:
        rel_dir = path.relative_to(DIST).parent.as_posix()
        parts = [] if rel_dir == "." else rel_dir.split("/")
        for depth in range(1, len(parts) + 1):
            key = "/".join(parts[:depth])
            dir_ids.setdefault(key, f"dir_{len(dir_ids):04d}")

    def children_of(parent: str) -> list[str]:
        prefix = "" if parent == "" else parent + "/"
        found = []
        for key in dir_ids:
            if key == "" or not key.startswith(prefix):
                continue
            rest = key[len(prefix):]
            if "/" not in rest:
                found.append(key)
        return sorted(found, key=str.lower)

    lines: list[str] = []
    add = lines.append

    add('<?xml version="1.0" encoding="utf-8"?>')
    add('<!-- GENERATED by gen-wxs.py - do not edit by hand. -->')
    add('<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">')
    add(f'  <Package Name="Filesa COChat {VERSION}" Manufacturer="Filesa"')
    add(f'           Version="{PRODUCT_VERSION}" UpgradeCode="{UPGRADE_CODE}"')
    add('           Scope="perUser" Language="2052" Compressed="yes">')
    add(f'    <SummaryInformation Description="Filesa COChat {VERSION} 安装程序" Manufacturer="Filesa" />')
    add('    <MajorUpgrade DowngradeErrorMessage="已安装更高版本的 Filesa COChat，请先卸载后再安装。" />')
    add('    <MediaTemplate EmbedCab="yes" />')
    add('    <Icon Id="AppIcon" SourceFile="$(var.SourceDir)\\Assets\\icon.ico" />')
    add('    <Property Id="ARPPRODUCTICON" Value="AppIcon" />')
    add('    <Property Id="ARPNOREPAIR" Value="1" />')
    add('    <Property Id="ARPNOMODIFY" Value="1" />')
    add('    <Property Id="ARPHELPLINK" Value="https://github.com/li2012China/Filesa-COChat" />')
    add('')
    add('    <!-- Per-user install: %LOCALAPPDATA%\\Programs, no elevation. -->')
    add('    <StandardDirectory Id="LocalAppDataFolder">')
    add('      <Directory Id="ProgramsFolder" Name="Programs">')
    add('        <Directory Id="INSTALLFOLDER" Name="FilesaCOChat">')

    def emit_dirs(parent: str, indent: int) -> None:
        pad = " " * indent
        for key in children_of(parent):
            name = key.rsplit("/", 1)[-1]
            add(f'{pad}<Directory Id="{dir_ids[key]}" Name="{escape(name, ATTR_ESCAPES)}">')
            emit_dirs(key, indent + 2)
            add(f"{pad}</Directory>")

    emit_dirs("", 10)
    add('        </Directory>')
    add('      </Directory>')
    add('    </StandardDirectory>')
    add('    <StandardDirectory Id="ProgramMenuFolder">')
    add('      <Directory Id="AppMenuFolder" Name="Filesa COChat" />')
    add('    </StandardDirectory>')
    add('')
    add('    <Feature Id="MainFeature" Title="Filesa COChat" Level="1">')
    add('      <ComponentGroupRef Id="AppFiles" />')
    add('      <ComponentRef Id="cmp_Shortcut" />')
    add('    </Feature>')
    add('  </Package>')
    add('')
    add('  <Fragment>')
    add('    <ComponentGroup Id="AppFiles">')

    for index, path in enumerate(files, start=1):
        rel = path.relative_to(DIST).as_posix()
        rel_dir = path.relative_to(DIST).parent.as_posix()
        rel_dir = "" if rel_dir == "." else rel_dir
        source = "$(var.SourceDir)\\" + rel.replace("/", "\\")
        add(f'      <Component Id="cmp_{index:04d}" Directory="{dir_ids[rel_dir]}"')
        add(f'                 Guid="{guid_for(rel)}">')
        add(f'        <File Id="fil_{index:04d}" Source="{escape(source, ATTR_ESCAPES)}" KeyPath="yes" />')
        add('      </Component>')

    add('    </ComponentGroup>')
    add('  </Fragment>')
    add('')
    add('  <Fragment>')
    add('    <!-- Start-menu shortcut + the HKCU key that makes it a per-user component. -->')
    add('    <Component Id="cmp_Shortcut" Directory="AppMenuFolder" Guid="' +
        guid_for("__shortcut__") + '">')
    add('      <Shortcut Id="StartMenuShortcut" Name="Filesa COChat"')
    add('                Description="局域网多人聊天 · 无需专用服务器"')
    add(f'                Target="[INSTALLFOLDER]{EXE_NAME}" WorkingDirectory="INSTALLFOLDER"')
    add('                Icon="AppIcon" />')
    add('      <RemoveFolder Id="rm_AppMenuFolder" Directory="AppMenuFolder" On="uninstall" />')
    add('      <RemoveFolder Id="rm_InstallFolder" Directory="INSTALLFOLDER" On="uninstall" />')
    add('      <RegistryValue Root="HKCU" Key="Software\\Filesa\\COChat" Name="InstallDir"')
    add('                     Type="string" Value="[INSTALLFOLDER]" KeyPath="yes" />')
    add('    </Component>')
    add('  </Fragment>')
    add('</Wix>')

    out = HERE / "Package.wxs"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} with {len(files)} files in {len(dir_ids) - 1} subdirectories")


if __name__ == "__main__":
    main()
